#!/usr/bin/env node
/**
 * Sitemap builder.
 *
 * The sitemap is the one file a crawler reads to learn what a site has. It
 * was hand-written, and it was out of date: the traffic page was not in it,
 * and none of the 163 city scorecards were — which are the pages a reader
 * actually searches for ("Bangkok liveability score"), and the reason the
 * index exists.
 *
 * The static routes stay hand-written; the city pages are derived, because
 * they come from the dataset and the dataset changes. The build replaces the
 * block between the markers, so a hand edit inside the block is lost and a
 * hand edit outside it is safe.
 *
 * Usage: node scripts/build-sitemap.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SITEMAP = join(ROOT, "public/sitemap.xml");
const ORIGIN = "https://slic.nonarkara.org";

const data = JSON.parse(readFileSync(join(ROOT, "src/data/publishedRankingData.json"), "utf8"));
const cities = Array.isArray(data) ? data : data.cities;
if (!Array.isArray(cities) || cities.length === 0) {
  console.error("the published dataset has no cities — the sitemap was not written");
  process.exit(1);
}

const cityUrls = cities
  .map((c) => c.cityId)
  .filter(Boolean)
  .sort()
  .map(
    (id) => `  <url>
    <loc>${ORIGIN}/city/${id}</loc>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
`,
  )
  .join("\n");

let xml = readFileSync(SITEMAP, "utf8");

// The traffic page is published and linked from the footer; it belongs here.
if (!xml.includes(`${ORIGIN}/traffic`)) {
  const block = `  <url>
    <loc>${ORIGIN}/traffic</loc>
    <changefreq>daily</changefreq>
    <priority>0.6</priority>
  </url>
`;
  xml = xml.replace("</urlset>", `${block}\n</urlset>`);
}

const START = "  <!-- CITY PAGES: generated by scripts/build-sitemap.mjs -->";
const END = "  <!-- END CITY PAGES -->";
const generated = `${START}\n${cityUrls}\n${END}`;

if (xml.includes(START) && xml.includes(END)) {
  const start = xml.indexOf(START);
  const end = xml.indexOf(END) + END.length;
  xml = xml.slice(0, start) + generated + xml.slice(end);
} else {
  xml = xml.replace("</urlset>", `${generated}\n\n</urlset>`);
}

writeFileSync(SITEMAP, xml);
const count = (xml.match(/<loc>/g) ?? []).length;
console.log(`sitemap: ${count} urls — ${cities.length} city pages, ${count - cities.length} other`);
